//! Contract → TypeScript AST lowering.

use std::collections::{BTreeMap, BTreeSet, HashMap};

use crate::diag::Diagnostic;
use crate::ir::{
    Contract, Endpoint, ErrorDecl, Field, Optionality, Primitive, RequestBody, SuccessBody,
    SuccessTransport, SymbolId, TypeDecl, TypeExpr, TypeShape,
};

use super::ast::{Expr, InterfaceField, Item, MarkKind, MarkRef, ObjectEntry};
use super::print::Printer;
use super::{GenOptions, GeneratedFile, GeneratedPackage, Mark};

const HEADER: &str = "// Generated by typeweld. Do not edit.\n";
const RUNTIME: &str = "@typeweld/effect-runtime";
const COMPAT: &str = "@typeweld/effect-runtime/compat";

pub fn lower(contract: &Contract, options: &GenOptions) -> (GeneratedPackage, Vec<Diagnostic>) {
    let mut cx = Lowering {
        contract,
        diagnostics: Vec::new(),
        files: Vec::new(),
        marks: Vec::new(),
    };

    cx.schemas_file();
    cx.errors_file();
    cx.client_file();
    let modules = cx.endpoint_files();
    cx.index_file(&modules);
    cx.package_json();
    cx.tsconfig_json(options);

    (
        GeneratedPackage {
            files: cx.files,
            marks: cx.marks,
        },
        cx.diagnostics,
    )
}

struct Lowering<'a> {
    contract: &'a Contract,
    diagnostics: Vec<Diagnostic>,
    files: Vec<GeneratedFile>,
    marks: Vec<Mark>,
}

impl<'a> Lowering<'a> {
    #[allow(clippy::similar_names)]
    fn emit(&mut self, path: &str, items: &[Item]) {
        let mut printer = Printer::new(HEADER);
        for item in items {
            printer.item(item);
        }
        let (contents, printed) = printer.finish();
        self.marks
            .extend(super::finish_marks(path, &contents, printed));
        self.files.push(GeneratedFile {
            path: path.to_owned(),
            contents,
        });
    }

    // ===== schemas.ts =====

    #[allow(clippy::too_many_lines)]
    fn schemas_file(&mut self) {
        let sorted = self.topo_sorted_types();
        let mut items = vec![Item::Import {
            type_only: false,
            names: vec!["Schema".to_owned()],
            from: COMPAT.to_owned(),
        }];

        for decl in sorted {
            items.push(Item::Raw(String::new()));
            let mark = MarkRef {
                symbol_id: decl.id.clone(),
                kind: MarkKind::Type,
            };

            // Explicit type declarations come first: they are what accessor
            // signatures reference and what cross-language rename anchors to
            // (tsserver renames concrete interface properties through user
            // code; properties derived via `typeof Schema.Type` mapped types
            // do not propagate).
            match &decl.shape {
                TypeShape::Struct { fields } => {
                    items.push(Item::Interface {
                        doc: decl.docs.clone(),
                        name: decl.ts_name.clone(),
                        mark: Some(mark.clone()),
                        fields: self.interface_fields(fields),
                    });
                }
                TypeShape::Enum { variants } => {
                    let mut names = Vec::new();
                    for variant in variants {
                        let variant_name = format!("{}{}", decl.ts_name, variant.rust_name);
                        let mut fields = vec![InterfaceField {
                            doc: None,
                            name: "_tag".to_owned(),
                            optional: false,
                            ty: format!("\"{}\"", variant.wire_name),
                            mark: Some(MarkRef {
                                symbol_id: variant.id.clone(),
                                kind: MarkKind::EnumVariant,
                            }),
                        }];
                        fields.extend(self.interface_fields(&variant.fields));
                        items.push(Item::Interface {
                            doc: variant.docs.clone(),
                            name: variant_name.clone(),
                            mark: None,
                            fields,
                        });
                        names.push(variant_name);
                    }
                    items.push(Item::TypeAlias {
                        doc: decl.docs.clone(),
                        name: decl.ts_name.clone(),
                        mark: Some(mark.clone()),
                        ty: names.join(" | "),
                    });
                }
                TypeShape::Newtype(inner) => {
                    let ty = {
                        let mut scratch = EndpointImports::default();
                        self.ts_type(inner, &mut scratch)
                    };
                    items.push(Item::TypeAlias {
                        doc: decl.docs.clone(),
                        name: decl.ts_name.clone(),
                        mark: Some(mark.clone()),
                        ty,
                    });
                }
            }

            let value = match &decl.shape {
                TypeShape::Struct { fields } => {
                    Expr::call("Schema.Struct", vec![self.fields_object(fields)])
                }
                TypeShape::Enum { variants } => {
                    let members = variants
                        .iter()
                        .map(|variant| {
                            let mut entries = vec![ObjectEntry {
                                key: "_tag".to_owned(),
                                value: Expr::Marked(
                                    MarkRef {
                                        symbol_id: variant.id.clone(),
                                        kind: MarkKind::EnumVariant,
                                    },
                                    Box::new(Expr::call(
                                        "Schema.Literal",
                                        vec![Expr::Str(variant.wire_name.clone())],
                                    )),
                                ),
                                mark: None,
                            }];
                            entries.extend(self.field_entries(&variant.fields));
                            Expr::call("Schema.Struct", vec![Expr::Object(entries)])
                        })
                        .collect();
                    Expr::call("Schema.Union", vec![Expr::Array(members)])
                }
                TypeShape::Newtype(inner) => self.schema_expr(inner),
            };
            items.push(Item::Const {
                doc: None,
                name: decl.ts_name.clone(),
                mark: Some(mark),
                ty: None,
                value,
                as_const: false,
            });
        }

        self.emit("schemas.ts", &items);
    }

    /// Schema consts must be declared before use; cycles are unsupported.
    #[allow(clippy::items_after_statements)]
    fn topo_sorted_types(&mut self) -> Vec<&'a TypeDecl> {
        let by_id: HashMap<&'a SymbolId, &'a TypeDecl> = self
            .contract
            .types
            .iter()
            .map(|decl| (&decl.id, decl))
            .collect();

        let mut sorted: Vec<&'a TypeDecl> = Vec::new();
        let mut state: HashMap<&'a SymbolId, u8> = HashMap::new(); // 1 = visiting, 2 = done
        let mut cycle_reported = false;

        fn refs(decl: &TypeDecl) -> Vec<&SymbolId> {
            fn collect<'e>(expr: &'e TypeExpr, out: &mut Vec<&'e SymbolId>) {
                match expr {
                    TypeExpr::Named(type_ref) => out.push(&type_ref.id),
                    TypeExpr::Option(inner) | TypeExpr::List(inner) => collect(inner, out),
                    TypeExpr::Map { key, value } => {
                        collect(key, out);
                        collect(value, out);
                    }
                    TypeExpr::Primitive(_) | TypeExpr::External(_) => {}
                }
            }
            let mut out = Vec::new();
            match &decl.shape {
                TypeShape::Struct { fields } => {
                    for field in fields {
                        collect(&field.ty, &mut out);
                    }
                }
                TypeShape::Enum { variants } => {
                    for variant in variants {
                        for field in &variant.fields {
                            collect(&field.ty, &mut out);
                        }
                    }
                }
                TypeShape::Newtype(inner) => collect(inner, &mut out),
            }
            out
        }

        #[allow(clippy::too_many_arguments)]
        fn visit<'a>(
            decl: &'a TypeDecl,
            by_id: &HashMap<&SymbolId, &'a TypeDecl>,
            state: &mut HashMap<&'a SymbolId, u8>,
            sorted: &mut Vec<&'a TypeDecl>,
            diagnostics: &mut Vec<Diagnostic>,
            cycle_reported: &mut bool,
        ) {
            match state.get(&decl.id) {
                Some(2) => return,
                Some(1) => {
                    if !*cycle_reported {
                        *cycle_reported = true;
                        diagnostics.push(Diagnostic::error(
                            "recursive-type",
                            format!(
                                "API type `{}` is recursive; recursive types are not supported \
                                 by the generator yet",
                                decl.ts_name
                            ),
                            Some(decl.spans.name.clone()),
                        ));
                    }
                    return;
                }
                _ => {}
            }
            state.insert(&decl.id, 1);
            for reference in refs(decl) {
                if let Some(target) = by_id.get(reference) {
                    visit(target, by_id, state, sorted, diagnostics, cycle_reported);
                }
            }
            state.insert(&decl.id, 2);
            sorted.push(decl);
        }

        for decl in &self.contract.types {
            visit(
                decl,
                &by_id,
                &mut state,
                &mut sorted,
                &mut self.diagnostics,
                &mut cycle_reported,
            );
        }
        sorted
    }

    fn fields_object(&mut self, fields: &[Field]) -> Expr {
        Expr::Object(self.field_entries(fields))
    }

    /// Interface properties matching the schema's decoded `Type` exactly.
    fn interface_fields(&mut self, fields: &[Field]) -> Vec<InterfaceField> {
        fields
            .iter()
            .map(|field| {
                let base = {
                    let mut scratch = EndpointImports::default();
                    self.ts_type(&field.ty, &mut scratch)
                };
                let (optional, ty) = match field.optionality {
                    Optionality::Required => (false, base),
                    Optionality::Nullable => (false, format!("{base} | null")),
                    Optionality::Optional => (true, base),
                    Optionality::OptionalNullable => (true, format!("{base} | null")),
                };
                InterfaceField {
                    doc: field.docs.clone(),
                    name: object_key(&field.wire_name),
                    optional,
                    ty,
                    mark: Some(MarkRef {
                        symbol_id: field.id.clone(),
                        kind: MarkKind::Field,
                    }),
                }
            })
            .collect()
    }

    fn field_entries(&mut self, fields: &[Field]) -> Vec<ObjectEntry> {
        fields
            .iter()
            .map(|field| {
                let base = self.schema_expr(&field.ty);
                let value = match field.optionality {
                    Optionality::Required => base,
                    Optionality::Nullable => Expr::call("Schema.NullOr", vec![base]),
                    Optionality::Optional => Expr::call("Schema.optionalKey", vec![base]),
                    Optionality::OptionalNullable => Expr::call(
                        "Schema.optionalKey",
                        vec![Expr::call("Schema.NullOr", vec![base])],
                    ),
                };
                ObjectEntry {
                    key: object_key(&field.wire_name),
                    value,
                    mark: Some(MarkRef {
                        symbol_id: field.id.clone(),
                        kind: MarkKind::FieldKey,
                    }),
                }
            })
            .collect()
    }

    fn schema_expr(&mut self, ty: &TypeExpr) -> Expr {
        match ty {
            TypeExpr::Primitive(Primitive::Bool) => Expr::ident("Schema.Boolean"),
            TypeExpr::Primitive(Primitive::String) => Expr::ident("Schema.String"),
            TypeExpr::Primitive(_) => Expr::ident("Schema.Number"),
            TypeExpr::External(external) => match external {
                crate::ir::ExternalType::JsonValue => Expr::ident("Schema.Unknown"),
                _ => Expr::ident("Schema.String"),
            },
            TypeExpr::Named(type_ref) => {
                if self.is_error_ref(&type_ref.id) {
                    self.diagnostics.push(Diagnostic::error(
                        "error-as-type",
                        format!(
                            "API error `{}` is used as a field type; declare a separate Api enum \
                             instead",
                            type_ref.name
                        ),
                        None,
                    ));
                }
                Expr::ident(type_ref.name.clone())
            }
            TypeExpr::Option(inner) => {
                let inner = self.schema_expr(inner);
                Expr::call("Schema.NullOr", vec![inner])
            }
            TypeExpr::List(inner) => {
                let inner = self.schema_expr(inner);
                Expr::call("Schema.Array", vec![inner])
            }
            TypeExpr::Map { value, .. } => {
                let value = self.schema_expr(value);
                Expr::call("Schema.Record", vec![Expr::ident("Schema.String"), value])
            }
        }
    }

    fn is_error_ref(&self, id: &SymbolId) -> bool {
        self.contract.errors.iter().any(|decl| &decl.id == id)
    }

    // ===== errors.ts =====

    fn errors_file(&mut self) {
        let mut items = Vec::new();
        let schema_imports = self.error_schema_imports();
        items.push(Item::Import {
            type_only: true,
            names: vec!["ApiClientError".to_owned()],
            from: RUNTIME.to_owned(),
        });
        items.push(Item::Import {
            type_only: false,
            names: vec!["decodeWithSchema".to_owned()],
            from: RUNTIME.to_owned(),
        });
        items.push(Item::Import {
            type_only: false,
            names: vec!["Effect".to_owned(), "Schema".to_owned()],
            from: COMPAT.to_owned(),
        });
        if !schema_imports.is_empty() {
            items.push(Item::Import {
                type_only: false,
                names: schema_imports,
                from: "./schemas".to_owned(),
            });
        }

        let error_decls: Vec<ErrorDecl> = self.contract.errors.clone();
        for decl in &error_decls {
            for variant in &decl.variants {
                items.push(Item::Raw(String::new()));
                let fields = self.field_entries(&variant.fields);
                items.push(Item::Class {
                    doc: variant.docs.clone(),
                    name: variant.tag.clone(),
                    mark: Some(MarkRef {
                        symbol_id: variant.id.clone(),
                        kind: MarkKind::ErrorVariant,
                    }),
                    extends: Expr::Call(
                        Box::new(Expr::call(
                            format!("Schema.TaggedErrorClass<{}>", variant.tag),
                            Vec::new(),
                        )),
                        vec![Expr::Str(variant.tag.clone()), Expr::Object(fields)],
                    ),
                });
            }

            let mark = MarkRef {
                symbol_id: decl.id.clone(),
                kind: MarkKind::Error,
            };
            let variant_names: Vec<String> = decl
                .variants
                .iter()
                .map(|variant| variant.tag.clone())
                .collect();
            items.push(Item::Raw(String::new()));
            items.push(Item::TypeAlias {
                doc: decl.docs.clone(),
                name: decl.ts_name.clone(),
                mark: Some(mark.clone()),
                ty: variant_names.join(" | "),
            });
            items.push(Item::Const {
                doc: None,
                name: decl.ts_name.clone(),
                mark: Some(mark),
                ty: None,
                value: Expr::call(
                    "Schema.Union",
                    vec![Expr::Array(
                        variant_names
                            .iter()
                            .map(|name| Expr::ident(name.clone()))
                            .collect(),
                    )],
                ),
                as_const: false,
            });

            let statuses: BTreeSet<u16> =
                decl.variants.iter().map(|variant| variant.status).collect();
            let cases = statuses
                .iter()
                .map(|status| format!("    case {status}:"))
                .collect::<Vec<_>>()
                .join("\n");
            items.push(Item::Raw(String::new()));
            items.push(Item::Raw(format!(
                "export const decode{name} = (\n  status: number,\n  input: unknown,\n): \
                 Effect.Effect<{name}, ApiClientError> | undefined => {{\n  switch (status) \
                 {{\n{cases}\n      return decodeWithSchema(input, {name})\n    default:\n      \
                 return undefined\n  }}\n}}",
                name = decl.ts_name,
            )));
        }

        self.emit("errors.ts", &items);
    }

    fn error_schema_imports(&mut self) -> Vec<String> {
        let mut names = BTreeSet::new();
        let errors = self.contract.errors.clone();
        for decl in &errors {
            for variant in &decl.variants {
                for field in &variant.fields {
                    collect_named(&field.ty, &mut names);
                }
            }
        }
        names.into_iter().collect()
    }

    // ===== client.ts =====

    fn client_file(&mut self) {
        let key = format!("{}/ApiConfig", self.contract.package.ts_package);
        let items = vec![
            Item::Import {
                type_only: true,
                names: vec!["FetchClientConfig".to_owned()],
                from: RUNTIME.to_owned(),
            },
            Item::Import {
                type_only: false,
                names: vec!["Context".to_owned(), "Layer".to_owned()],
                from: COMPAT.to_owned(),
            },
            Item::Raw(String::new()),
            Item::Class {
                doc: Some("Configuration service consumed by every generated accessor.".to_owned()),
                name: "ApiConfig".to_owned(),
                mark: None,
                extends: Expr::Call(
                    Box::new(Expr::call(
                        "Context.Service<ApiConfig, FetchClientConfig>",
                        Vec::new(),
                    )),
                    vec![Expr::Str(key)],
                ),
            },
            Item::Raw(String::new()),
            Item::FnConst {
                doc: Some("Provides the API configuration to generated accessors.".to_owned()),
                name: "layer".to_owned(),
                mark: None,
                params: vec![("config".to_owned(), "FetchClientConfig".to_owned())],
                ret: "Layer.Layer<ApiConfig>".to_owned(),
                body: Expr::call(
                    "Layer.succeed",
                    vec![
                        Expr::ident("ApiConfig"),
                        Expr::member_call("ApiConfig", "of", vec![Expr::ident("config")]),
                    ],
                ),
            },
        ];
        self.emit("client.ts", &items);
    }

    // ===== endpoints/<module>.ts =====

    fn endpoint_files(&mut self) -> Vec<String> {
        let mut modules: BTreeMap<String, Vec<Endpoint>> = BTreeMap::new();
        for endpoint in &self.contract.endpoints {
            modules
                .entry(endpoint.ts_module.clone())
                .or_default()
                .push(endpoint.clone());
        }

        let names: Vec<String> = modules.keys().cloned().collect();
        for (module, endpoints) in modules {
            self.endpoint_file(&module, &endpoints);
        }
        names
    }

    fn endpoint_file(&mut self, module: &str, endpoints: &[Endpoint]) {
        let mut imports = EndpointImports::default();
        let mut body_items: Vec<Item> = Vec::new();

        for endpoint in endpoints {
            self.endpoint_items(endpoint, &mut imports, &mut body_items);
        }

        let mut items = imports.into_items(self.error_names(endpoints));
        items.append(&mut body_items);
        self.emit(&format!("endpoints/{module}.ts"), &items);
    }

    #[allow(clippy::unused_self)]
    fn error_names(&self, endpoints: &[Endpoint]) -> Vec<String> {
        let mut names = BTreeSet::new();
        for endpoint in endpoints {
            for error in &endpoint.errors {
                names.insert(error.name.clone());
                names.insert(format!("decode{}", error.name));
            }
        }
        names.into_iter().collect()
    }

    #[allow(clippy::too_many_lines)]
    fn endpoint_items(
        &mut self,
        endpoint: &Endpoint,
        imports: &mut EndpointImports,
        items: &mut Vec<Item>,
    ) {
        let pascal = {
            let mut chars = endpoint.ts_name.chars();
            chars
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        };
        let args_name = format!("{pascal}Args");
        let has_args = !endpoint.request.path_params.is_empty()
            || !endpoint.request.query_params.is_empty()
            || endpoint.request.body.is_some();

        // Args interface.
        if has_args {
            let mut fields = Vec::new();
            for param in &endpoint.request.path_params {
                fields.push(InterfaceField {
                    doc: None,
                    name: object_key(&param.name),
                    optional: false,
                    ty: self.ts_type(&param.ty, imports),
                    mark: Some(MarkRef {
                        symbol_id: param.id.clone(),
                        kind: MarkKind::Param,
                    }),
                });
            }
            for param in &endpoint.request.query_params {
                fields.push(InterfaceField {
                    doc: None,
                    name: object_key(&param.name),
                    optional: !param.required,
                    ty: self.ts_type(&param.ty, imports),
                    mark: Some(MarkRef {
                        symbol_id: param.id.clone(),
                        kind: MarkKind::Param,
                    }),
                });
            }
            match &endpoint.request.body {
                Some(RequestBody::Json(ty)) => fields.push(InterfaceField {
                    doc: None,
                    name: "body".to_owned(),
                    optional: false,
                    ty: self.ts_type(ty, imports),
                    mark: None,
                }),
                Some(RequestBody::Binary) => {
                    imports.runtime_types.insert("BinaryRequestBody".to_owned());
                    fields.push(InterfaceField {
                        doc: None,
                        name: "body".to_owned(),
                        optional: false,
                        ty: "BinaryRequestBody".to_owned(),
                        mark: None,
                    });
                }
                None => {}
            }
            items.push(Item::Raw(String::new()));
            items.push(Item::Interface {
                doc: None,
                name: args_name.clone(),
                mark: None,
                fields,
            });
        }

        // Route metadata const.
        items.push(Item::Raw(String::new()));
        items.push(Item::Const {
            doc: None,
            name: format!("{}Route", endpoint.ts_name),
            mark: None,
            ty: None,
            value: Expr::Object(vec![
                ObjectEntry {
                    key: "method".to_owned(),
                    value: Expr::Str(endpoint.method.as_str().to_owned()),
                    mark: None,
                },
                ObjectEntry {
                    key: "path".to_owned(),
                    value: Expr::Str(endpoint.route.clone()),
                    mark: None,
                },
            ]),
            as_const: true,
        });

        // The accessor.
        let args_ty = if has_args { args_name.as_str() } else { "void" };
        let error_name = endpoint.errors.first().map(|error| error.name.clone());
        let error_union = match &error_name {
            Some(name) => format!("{name} | ApiClientError"),
            None => "ApiClientError".to_owned(),
        };
        let domain_error = error_name.as_deref().unwrap_or("never");

        let endpoint_object = self.endpoint_object(endpoint, imports, &error_name);
        let invoke_arg = if has_args { "args" } else { "void 0" };

        let (factory, success_ty, ret, body) =
            match (&endpoint.success.transport, &endpoint.success.body) {
                (SuccessTransport::Sse, SuccessBody::Stream(item)) => {
                    imports.compat.insert("Stream".to_owned());
                    imports.compat.insert("Effect".to_owned());
                    imports.runtime.insert("makeSseClient".to_owned());
                    let item_ty = self.ts_type(item, imports);
                    let ret = format!("Stream.Stream<{item_ty}, {error_union}, ApiConfig>");
                    let client = Expr::Call(
                        Box::new(Expr::Call(
                            Box::new(Expr::Raw(format!(
                                "makeSseClient<{args_ty}, {item_ty}, {domain_error}>"
                            ))),
                            vec![Expr::ident("config"), endpoint_object],
                        )),
                        vec![Expr::ident(invoke_arg)],
                    );
                    let body = Expr::call(
                        "Stream.unwrap",
                        vec![Expr::member_call(
                            "ApiConfig",
                            "use",
                            vec![Expr::Arrow {
                                params: vec!["config".to_owned()],
                                body: Box::new(Expr::call("Effect.succeed", vec![client])),
                            }],
                        )],
                    );
                    ("makeSseClient", item_ty, ret, body)
                }
                (SuccessTransport::BinaryDownload, _) => {
                    imports.compat.insert("Effect".to_owned());
                    imports
                        .runtime
                        .insert("makeBinaryDownloadClient".to_owned());
                    let ret = format!("Effect.Effect<Uint8Array, {error_union}, ApiConfig>");
                    let client = Expr::Call(
                        Box::new(Expr::Call(
                            Box::new(Expr::Raw(format!(
                                "makeBinaryDownloadClient<{args_ty}, {domain_error}>"
                            ))),
                            vec![Expr::ident("config"), endpoint_object],
                        )),
                        vec![Expr::ident(invoke_arg)],
                    );
                    let body = Expr::member_call(
                        "ApiConfig",
                        "use",
                        vec![Expr::Arrow {
                            params: vec!["config".to_owned()],
                            body: Box::new(client),
                        }],
                    );
                    (
                        "makeBinaryDownloadClient",
                        "Uint8Array".to_owned(),
                        ret,
                        body,
                    )
                }
                (transport, body_shape) => {
                    imports.compat.insert("Effect".to_owned());
                    let factory = if matches!(transport, SuccessTransport::BinaryUpload) {
                        "makeBinaryUploadClient"
                    } else {
                        "makeUnaryHttpClient"
                    };
                    imports.runtime.insert(factory.to_owned());
                    let success_ty = match body_shape {
                        SuccessBody::Json(ty) => self.ts_type(ty, imports),
                        _ => "void".to_owned(),
                    };
                    let ret = format!("Effect.Effect<{success_ty}, {error_union}, ApiConfig>");
                    let client = Expr::Call(
                        Box::new(Expr::Call(
                            Box::new(Expr::Raw(format!(
                                "{factory}<{args_ty}, {success_ty}, {domain_error}>"
                            ))),
                            vec![Expr::ident("config"), endpoint_object],
                        )),
                        vec![Expr::ident(invoke_arg)],
                    );
                    let body = Expr::member_call(
                        "ApiConfig",
                        "use",
                        vec![Expr::Arrow {
                            params: vec!["config".to_owned()],
                            body: Box::new(client),
                        }],
                    );
                    (factory, success_ty, ret, body)
                }
            };
        let _ = (factory, success_ty);

        items.push(Item::Raw(String::new()));
        items.push(Item::FnConst {
            doc: endpoint.docs.clone(),
            name: endpoint.ts_name.clone(),
            mark: Some(MarkRef {
                symbol_id: endpoint.id.clone(),
                kind: MarkKind::Endpoint,
            }),
            params: if has_args {
                vec![("args".to_owned(), args_name)]
            } else {
                Vec::new()
            },
            ret,
            body,
        });
    }

    /// The runtime endpoint definition object passed to the client factory.
    #[allow(clippy::too_many_lines, clippy::ref_option)]
    fn endpoint_object(
        &mut self,
        endpoint: &Endpoint,
        imports: &mut EndpointImports,
        error_name: &Option<String>,
    ) -> Expr {
        let mut entries = vec![
            ObjectEntry {
                key: "method".to_owned(),
                value: Expr::Str(endpoint.method.as_str().to_owned()),
                mark: None,
            },
            ObjectEntry {
                key: "path".to_owned(),
                value: Expr::Str(endpoint.route.clone()),
                mark: None,
            },
        ];

        // encode
        let mut encode_entries = Vec::new();
        if !endpoint.request.path_params.is_empty() {
            let params = endpoint
                .request
                .path_params
                .iter()
                .map(|param| ObjectEntry {
                    key: object_key(&param.name),
                    value: Expr::Raw(args_access(&param.name)),
                    mark: None,
                })
                .collect();
            encode_entries.push(ObjectEntry {
                key: "path".to_owned(),
                value: Expr::Object(params),
                mark: None,
            });
        }
        if !endpoint.request.query_params.is_empty() {
            let params = endpoint
                .request
                .query_params
                .iter()
                .map(|param| ObjectEntry {
                    key: object_key(&param.name),
                    value: Expr::Raw(args_access(&param.name)),
                    mark: None,
                })
                .collect();
            encode_entries.push(ObjectEntry {
                key: "query".to_owned(),
                value: Expr::Object(params),
                mark: None,
            });
        }
        match &endpoint.request.body {
            Some(RequestBody::Json(ty)) => {
                imports.runtime.insert("encodeWithSchema".to_owned());
                let schema = self.schema_expr_imported(ty, imports);
                encode_entries.push(ObjectEntry {
                    key: "body".to_owned(),
                    value: Expr::call(
                        "encodeWithSchema",
                        vec![Expr::Raw("args.body".to_owned()), schema],
                    ),
                    mark: None,
                });
            }
            Some(RequestBody::Binary) => {
                encode_entries.push(ObjectEntry {
                    key: "body".to_owned(),
                    value: Expr::Raw("args.body".to_owned()),
                    mark: None,
                });
                encode_entries.push(ObjectEntry {
                    key: "bodyKind".to_owned(),
                    value: Expr::Str("binary".to_owned()),
                    mark: None,
                });
            }
            None => {}
        }
        if !encode_entries.is_empty() {
            entries.push(ObjectEntry {
                key: "encode".to_owned(),
                value: Expr::Arrow {
                    params: vec!["args".to_owned()],
                    body: Box::new(Expr::Object(encode_entries)),
                },
                mark: None,
            });
        }

        // decodeSuccess
        match (&endpoint.success.transport, &endpoint.success.body) {
            (SuccessTransport::BinaryDownload, _) => {}
            (_, SuccessBody::Json(ty) | SuccessBody::Stream(ty)) => {
                imports.runtime.insert("decodeWithSchema".to_owned());
                let schema = self.schema_expr_imported(ty, imports);
                entries.push(ObjectEntry {
                    key: "decodeSuccess".to_owned(),
                    value: Expr::Arrow {
                        params: vec!["input".to_owned()],
                        body: Box::new(Expr::call(
                            "decodeWithSchema",
                            vec![Expr::ident("input"), schema],
                        )),
                    },
                    mark: None,
                });
            }
            _ => {
                imports.compat.insert("Effect".to_owned());
                entries.push(ObjectEntry {
                    key: "decodeSuccess".to_owned(),
                    value: Expr::Raw("() => Effect.succeed(undefined)".to_owned()),
                    mark: None,
                });
            }
        }

        if let Some(name) = error_name {
            entries.push(ObjectEntry {
                key: "decodeError".to_owned(),
                value: Expr::ident(format!("decode{name}")),
                mark: None,
            });
        }

        Expr::Object(entries)
    }

    /// Schema expression, registering schema imports for named references and
    /// the `Schema` module import for composite expressions.
    fn schema_expr_imported(&mut self, ty: &TypeExpr, imports: &mut EndpointImports) -> Expr {
        let mut names = BTreeSet::new();
        collect_named(ty, &mut names);
        imports.schemas.extend(names);
        if !matches!(ty, TypeExpr::Named(_)) {
            imports.compat.insert("Schema".to_owned());
        }
        self.schema_expr(ty)
    }

    #[allow(clippy::self_only_used_in_recursion)]
    fn ts_type(&mut self, ty: &TypeExpr, imports: &mut EndpointImports) -> String {
        match ty {
            TypeExpr::Primitive(Primitive::Bool) => "boolean".to_owned(),
            TypeExpr::Primitive(Primitive::String) => "string".to_owned(),
            TypeExpr::Primitive(_) => "number".to_owned(),
            TypeExpr::External(crate::ir::ExternalType::JsonValue) => "unknown".to_owned(),
            TypeExpr::External(_) => "string".to_owned(),
            TypeExpr::Named(type_ref) => {
                imports.schemas.insert(type_ref.name.clone());
                type_ref.name.clone()
            }
            TypeExpr::Option(inner) => format!("{} | null", self.ts_type(inner, imports)),
            TypeExpr::List(inner) => format!("ReadonlyArray<{}>", self.ts_type(inner, imports)),
            TypeExpr::Map { value, .. } => {
                format!("Readonly<Record<string, {}>>", self.ts_type(value, imports))
            }
        }
    }

    // ===== index.ts and package.json =====

    fn index_file(&mut self, modules: &[String]) {
        let mut items = vec![
            Item::ExportStar {
                from: "./schemas".to_owned(),
            },
            Item::ExportStar {
                from: "./errors".to_owned(),
            },
            Item::ExportNames {
                names: vec!["ApiConfig".to_owned(), "layer".to_owned()],
                from: "./client".to_owned(),
            },
        ];
        for module in modules {
            items.push(Item::ExportStarAs {
                alias: module.clone(),
                from: format!("./endpoints/{module}"),
            });
        }
        self.emit("index.ts", &items);
    }

    fn package_json(&mut self) {
        let contents = format!(
            "{{\n  \"name\": \"{}\",\n  \"version\": \"0.0.0\",\n  \"private\": true,\n  \
             \"type\": \"module\",\n  \"sideEffects\": false\n}}\n",
            self.contract.package.ts_package
        );
        self.files.push(GeneratedFile {
            path: "package.json".to_owned(),
            contents,
        });
    }

    /// A tsconfig spanning the bindings AND the app sources that use them.
    ///
    /// tsserver assigns generated files to this project (the nearest
    /// tsconfig), so navigation and rename initiated inside the bindings see
    /// the application code — the language server's TypeScript backend
    /// depends on this for cross-language field renames.
    fn tsconfig_json(&mut self, options: &GenOptions) {
        // Path from the package directory back up to the workspace root.
        let rel_root = options.package_dir.as_ref().map(|dir| {
            let ups = dir.components().count();
            let mut prefix = String::new();
            for _ in 0..ups {
                prefix.push_str("../");
            }
            prefix
        });

        let ts_package = &self.contract.package.ts_package;
        let mut paths = vec![
            (ts_package.clone(), "./index.ts".to_owned()),
            (format!("{ts_package}/*"), "./*".to_owned()),
        ];
        let mut includes = vec!["\"./**/*.ts\"".to_owned()];

        if let Some(rel_root) = &rel_root {
            // The app's node_modules hosts the runtime and effect; derive its
            // location from the first app source glob ("app/src/**/*.ts").
            let app_dir = options
                .app_src
                .first()
                .and_then(|glob| glob.split('/').next())
                .filter(|segment| !segment.is_empty() && !segment.contains('*'));
            if let Some(app_dir) = app_dir {
                let modules = format!("{rel_root}{app_dir}/node_modules");
                paths.push((
                    "@typeweld/effect-runtime".to_owned(),
                    format!("{modules}/@typeweld/effect-runtime/src/index.ts"),
                ));
                paths.push((
                    "@typeweld/effect-runtime/compat".to_owned(),
                    format!("{modules}/@typeweld/effect-runtime/src/compat.ts"),
                ));
                paths.push((
                    "effect".to_owned(),
                    format!("{modules}/effect/dist/index.d.ts"),
                ));
            }
            for glob in &options.app_src {
                includes.push(format!("\"{rel_root}{glob}\""));
            }
        }

        let paths = paths
            .iter()
            .map(|(name, target)| format!("      \"{name}\": [\"{target}\"]"))
            .collect::<Vec<_>>()
            .join(",\n");
        let includes = includes.join(", ");
        let contents = format!(
            "{{\n  \"compilerOptions\": {{\n    \"strict\": true,\n    \"noEmit\": true,\n    \
             \"target\": \"ES2022\",\n    \"module\": \"ESNext\",\n    \"moduleResolution\": \
             \"bundler\",\n    \"skipLibCheck\": true,\n    \"paths\": {{\n{paths}\n    }}\n  \
             }},\n  \"include\": [{includes}]\n}}\n"
        );
        self.files.push(GeneratedFile {
            path: "tsconfig.json".to_owned(),
            contents,
        });
    }
}

/// Per-file import accumulator for endpoint modules.
#[derive(Default)]
struct EndpointImports {
    /// Value imports from `@typeweld/effect-runtime`.
    runtime: BTreeSet<String>,
    /// Type-only imports from the runtime.
    runtime_types: BTreeSet<String>,
    /// Modules from `@typeweld/effect-runtime/compat` (Effect, Stream).
    compat: BTreeSet<String>,
    /// Named schema imports from `./schemas`.
    schemas: BTreeSet<String>,
}

impl EndpointImports {
    fn into_items(mut self, error_names: Vec<String>) -> Vec<Item> {
        self.runtime_types.insert("ApiClientError".to_owned());
        let mut items = vec![Item::Import {
            type_only: true,
            names: self.runtime_types.into_iter().collect(),
            from: RUNTIME.to_owned(),
        }];
        if !self.runtime.is_empty() {
            items.push(Item::Import {
                type_only: false,
                names: self.runtime.into_iter().collect(),
                from: RUNTIME.to_owned(),
            });
        }
        if !self.compat.is_empty() {
            items.push(Item::Import {
                type_only: false,
                names: self.compat.into_iter().collect(),
                from: COMPAT.to_owned(),
            });
        }
        items.push(Item::Import {
            type_only: false,
            names: vec!["ApiConfig".to_owned()],
            from: "../client".to_owned(),
        });
        if !self.schemas.is_empty() {
            items.push(Item::Import {
                type_only: false,
                names: self.schemas.into_iter().collect(),
                from: "../schemas".to_owned(),
            });
        }
        if !error_names.is_empty() {
            items.push(Item::Import {
                type_only: false,
                names: error_names,
                from: "../errors".to_owned(),
            });
        }
        items
    }
}

fn collect_named(ty: &TypeExpr, names: &mut BTreeSet<String>) {
    match ty {
        TypeExpr::Named(type_ref) => {
            names.insert(type_ref.name.clone());
        }
        TypeExpr::Option(inner) | TypeExpr::List(inner) => collect_named(inner, names),
        TypeExpr::Map { key, value } => {
            collect_named(key, names);
            collect_named(value, names);
        }
        TypeExpr::Primitive(_) | TypeExpr::External(_) => {}
    }
}

/// Quotes object keys / interface fields that are not valid TS identifiers.
fn object_key(name: &str) -> String {
    let valid = !name.is_empty()
        && name
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_alphabetic() || first == '_' || first == '$')
        && name.chars().all(|character| {
            character.is_ascii_alphanumeric() || character == '_' || character == '$'
        });
    if valid {
        name.to_owned()
    } else {
        format!("\"{}\"", name.replace('"', "\\\""))
    }
}

/// `args.name` or `args["name"]` for non-identifier names.
fn args_access(name: &str) -> String {
    let quoted = object_key(name);
    if quoted.starts_with('"') {
        format!("args[{quoted}]")
    } else {
        format!("args.{name}")
    }
}
